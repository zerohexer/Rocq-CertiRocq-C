#!/usr/bin/env python3
"""mkloopspec.py > proved/KQLoopSpec.v : the equation and the induction principle of each recursion with a measure of lib/Loop.v,
from the generic theory of lib/LoopSpec.v (the one template below, once per form)."""
import itertools

HEAD = r'''(* proved/KQLoopSpec.v -- WHAT THE RECURSION WITH A MEASURE OF lib/Loop.v GUARANTEES (generated by tools/mkloopspec.py).

   For each form wfixN (numbers -> number), wfixNm (numbers and a memory read -> number), wfixmN (numbers and a memory -> memory):
     <form>_eq   the equation of the recursive function:  <form> meas F x = F (<form> meas F) x
     <form>_ind  a property of the function is proved by induction on the measure
   under the termination argument D: F calls rec only at an argument in the domain P of smaller measure (not below 0), that is,
   F gives the same answer for two recs that agree on all such arguments.  The measure and its budget are at most 2^60.
   `wf_dec` proves D for the usual bodies (a test, then rec at arguments the test makes smaller). *)
From Stdlib Require Import ZArith Lia Sint63.
Require Import KQ.KQRun KQ.KQSpec KQ.lib.Loop KQ.lib.LoopSpec.
From KQC Require Import KQMAuto.
Open Scope sint63_scope.
Notation Z_ := Sint63.to_Z.

(* the budget of a loop with measure v is at least v + 1 *)
(* facts about the arithmetic of a measure *)
Lemma sub1_Z (x : int) : (0 < Z_ x)%Z -> Z_ (x - 1) = (Z_ x - 1)%Z.
Proof. intro P. pose proof (to_Z_bounds x). rewrite sub_Z; change (Z_ 1) with 1%Z; lia. Qed.
Lemma add1_Z (x : int) : (Z_ x < 2 ^ 60)%Z -> Z_ (x + 1) = (Z_ x + 1)%Z.
Proof. intro P. pose proof (to_Z_bounds x). rewrite add_Z; change (Z_ 1) with 1%Z; lia. Qed.
Lemma rem_range (x y : int) : (0 <= Z_ x)%Z -> (0 < Z_ y)%Z -> (0 <= Z_ (Sint63.rem x y) < Z_ y)%Z.
Proof.
  intros X Y. rewrite Sint63.mod_spec. pose proof (Z.rem_bound_pos (Z_ x) (Z_ y) X Y). lia.
Qed.
Lemma div2_range (x : int) : (0 <= Z_ x)%Z -> (0 <= Z_ (Sint63.div x 2) <= Z_ x)%Z.
Proof.
  intros X. rewrite Sint63.div_spec by (right; change (Z_ 2) with 2%Z; lia). change (Z_ 2) with 2%Z.
  pose proof (Z.quot_div_nonneg (Z_ x) 2 X ltac:(lia)) as E. rewrite E.
  split; [apply Z.div_pos; lia | apply Z.div_le_upper_bound; lia].
Qed.

(* the comparisons in the hypotheses, as facts about the integers they stand for *)
Ltac wf_zify :=
  repeat match goal with
         | H : (_ <? _) = true |- _ => apply lt_Z in H
         | H : (_ <? _) = false |- _ => apply lt_Z_false in H
         | H : (_ <=? _) = true |- _ => apply le_Z in H
         | H : (_ <=? _) = false |- _ => apply le_Z_false in H
         | H : (_ =? _) = true |- _ => apply eq_Z in H
         | H : (_ =? _) = false |- _ => apply eq_Z_false in H
         end;
  try (change (Z_ 0) with 0%Z in *); try (change (Z_ 1) with 1%Z in *); try (change (Z_ 2) with 2%Z in *).

(* the facts of the usual measures, added where the goal mentions them *)
Ltac wf_facts :=
  repeat match goal with
         | |- context [Z_ (?x - 1)] =>
             lazymatch goal with
             | _ : Z_ (x - 1) = _ |- _ => fail
             | _ => let H := fresh "Hs" in assert (H : Z_ (x - 1) = (Z_ x - 1)%Z) by (apply sub1_Z; lia)
             end
         | |- context [Z_ (Sint63.rem ?x ?y)] =>
             lazymatch goal with
             | _ : (0 <= Z_ (Sint63.rem x y) < Z_ y)%Z |- _ => fail
             | _ => let H := fresh "Hr" in assert (H : (0 <= Z_ (Sint63.rem x y) < Z_ y)%Z) by (apply rem_range; lia)
             end
         | |- context [Z_ (Sint63.div ?x 2)] =>
             lazymatch goal with
             | _ : (0 <= Z_ (Sint63.div x 2) <= Z_ x)%Z |- _ => fail
             | _ => let H := fresh "Hd" in assert (H : (0 <= Z_ (Sint63.div x 2) <= Z_ x)%Z) by (apply div2_range; lia)
             end
         end.
(* the usual side goal: the call's argument is in the domain and its measure is smaller *)
Ltac wf_side := cbv beta in *; repeat match goal with H : _ /\ _ |- _ => destruct H end; wf_facts; try split; lia.
(* an equation between F's answers for two recs: closed when the two sides are the same, or each call of rec is at an argument
   that [side] shows is in the domain and of smaller measure *)
Ltac wf_close H side := first [ reflexivity | (timeout 5 (apply H); [ side | side ]) | (f_equal; wf_close H side) ].
Ltac wf_head t := match t with ?f _ => wf_head f | _ => t end.
Ltac wf_dec_finish H side :=
  (* the body of F is opened: the goal says what F does on one argument *)
  try (lazymatch goal with |- ?l = _ => let h := wf_head l in unfold h end);
  cbv beta;
  repeat match goal with |- context [if ?c then _ else _] => let E := fresh "E" in destruct c eqn:E end;
  wf_zify; wf_close H side.

Lemma budget_ge (v : int) : (0 <= Z_ v)%Z -> (Z_ v + 1 <= 2 ^ 60)%Z -> (Z_ v + 1 <= Z.of_nat (kq_nat (v + 1)))%Z.
Proof.
  intros V0 V1. pose proof (to_Z_bounds v) as B.
  assert (A : Z_ (v + 1) = (Z_ v + 1)%Z) by (rewrite add_Z; change (Z_ 1) with 1%Z; lia).
  rewrite (kq_nat_val (v + 1)); [lia | rewrite A; lia].
Qed.
'''

def forms():
    out = []
    for mem, res in ((False, 'int'), (True, 'int'), (True, 'mem')):
        for n in (1, 2, 3):
            if res == 'mem' and n == 3:
                continue
            name = 'wfix' + ('m' if res == 'mem' else '') + str(n) + ('m' if (mem and res == 'int') else '')
            out.append((name, n, mem, res))
    return out

def tup(vs):
    t = vs[0]
    for v in vs[1:]:
        t = '(' + t + ', ' + v + ')'
    return t

def pat(vs):
    t = vs[0]
    for v in vs[1:]:
        t = '[' + t + ' ' + v + ']'
    return t

def gen(name, n, mem, res):
    ints = ['a', 'b', 'c'][:n]
    ints2 = [v + "'" for v in ints]
    args = ints + (['s'] if mem else [])
    args2 = ints2 + (["s'"] if mem else [])
    IT = 'int'
    argT = ' -> '.join([IT] * n + (['mem'] if mem else []))
    recT = argT + ' -> ' + res
    prodT = ' * '.join([IT] * n + (['mem'] if mem else []))
    prodT = IT if len(args) == 1 else '(' + prodT + ')%type'
    sp = ' '.join(args)
    sp2 = ' '.join(args2)
    args3 = [v + '_' for v in args]
    sp3 = ' '.join(args3)
    mp3 = pat(args3)
    measT = ' -> '.join([IT] * (n + 1))
    meas_app = lambda vs: 'meas ' + ' '.join(vs[:n])
    Pty = ' -> '.join([IT] * n + (['mem'] if mem else []) + ['Prop'])
    default = 's' if res == 'mem' else '0'
    tpl = r'''
(* ---- {name} *)
Ltac {name}_dec_tac side := intros r1 r2 {sp} HP H; wf_dec_finish H side.
Section S_{name}.
Variables (meas : {measT}) (F : ({recT}) -> {argT} -> {res}) (P : {Pty}).
Definition {name}_dec : Prop :=
  forall (r1 r2 : {recT}) {sp}, P {sp} ->
    (forall {sp2}, P {sp2} -> (0 <= Z_ ({m2}) < Z_ ({m1}))%Z -> r1 {sp2} = r2 {sp2}) -> F r1 {sp} = F r2 {sp}.
Let A := {prodT}.
Let go : nat -> A -> {res} := fun k p => match p with {mt} => {name}_go k F {sp} end.
Let F' : (A -> {res}) -> A -> {res} := fun r p => match p with {mt} => F (fun {sp2} => r {tp2}) {sp} end.
Let m : A -> Z := fun p => match p with {mt} => Z_ ({m1}) end.
Let P' : A -> Prop := fun p => match p with {mt} => P {sp} end.
Let fuel : A -> nat := fun p => match p with {mt} => kq_nat ({m1} + 1) end.
Let H1 : forall k x, go (S k) x = F' (go k) x. Proof. intros k {mp}. reflexivity. Qed.
Let Hfuel : forall x, P' x -> (0 <= m x)%Z -> (m x + 1 <= 2 ^ 60)%Z -> (m x + 1 <= Z.of_nat (fuel x))%Z.
Proof. intros {mp} Px M0 M1. exact (budget_ge _ M0 M1). Qed.
Let Dec : {name}_dec -> dec F' m P'.
Proof.
  intros D r1 r2 {mp} Px H. exact (D (fun {sp2} => r1 {tp2}) (fun {sp2} => r2 {tp2}) {sp} Px (fun {sp2} P2 M => H {tp2} P2 M)).
Qed.

Theorem {name}_eq : {name}_dec -> forall {sp}, P {sp} -> (0 <= Z_ ({m1}))%Z -> (Z_ ({m1}) + 1 <= 2 ^ 60)%Z ->
  {name} meas F {sp} = F ({name} meas F) {sp}.
Proof.
  intros D {sp} Px M0 M1.
  exact (wf_wrapper_eq F' go m P' H1 fuel Hfuel (Dec D) {tp} Px M0 M1).
Qed.

Theorem {name}_ind (Q : {Qty}) : {name}_dec ->
  (forall {sp}, P {sp} -> (0 <= Z_ ({m1}))%Z -> (Z_ ({m1}) + 1 <= 2 ^ 60)%Z ->
     forall r : {recT}, (forall {sp2}, P {sp2} -> (0 <= Z_ ({m2}) < Z_ ({m1}))%Z -> Q {sp2} (r {sp2})) -> Q {sp} (F r {sp})) ->
  forall {sp}, P {sp} -> (0 <= Z_ ({m1}))%Z -> (Z_ ({m1}) + 1 <= 2 ^ 60)%Z -> Q {sp} ({name} meas F {sp}).
Proof.
  intros D S {sp} Px M0 M1.
  exact (wf_ind F' go m P' H1 fuel Hfuel (fun p v => match p with {mt} => Q {sp} v end) (Dec D)
           (ltac:(intros {mp3} Px_ M0_ M1_ r Hr; exact (S {sp3} Px_ M0_ M1_ (fun {sp2} => r {tp2}) (fun {sp2} P2 M => Hr {tp2} P2 M))))
           {tp} Px M0 M1).
Qed.
End S_{name}.
'''
    Qty = ' -> '.join([IT] * n + (['mem'] if mem else []) + [res, 'Prop'])
    return tpl.format(name=name, measT=measT, recT=recT, argT=argT, res=res, Pty=Pty, sp=sp, sp2=sp2,
                      m1=meas_app(args), m2=meas_app(args2), prodT=prodT, mp=pat(args),
                      tp=tup(args), tp2=tup(args2), mt=tup(args), sp3=sp3, mp3=mp3, default=default, Qty=Qty)

if __name__ == '__main__':
    print(HEAD)
    for f in forms():
        print(gen(*f))
